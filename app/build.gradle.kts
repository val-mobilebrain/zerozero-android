val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) {
        load(FileInputStream(file))
    }
}

fun releaseProp(name: String): String? =
    System.getenv(name) ?: localProperties.getProperty(name)

